import assert from 'node:assert/strict'
import { readFile, mkdir } from 'node:fs/promises'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const source = await readFile('public/embed/assistant.js', 'utf8')
const icon = await readFile('public/embed/icons/assistant-core.svg', 'utf8')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 900, height: 700 }, hasTouch: true })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.route('**/*', route => {
  const url = new URL(route.request().url())
  if (url.pathname.endsWith('.js')) return route.fulfill({ contentType: 'text/javascript; charset=utf-8', body: source })
  if (url.pathname.endsWith('.svg')) return route.fulfill({ contentType: 'image/svg+xml', body: icon })
  if (url.hostname === 'child.test' || url.pathname === '/embed/chat') return route.fulfill({ contentType: 'text/html', body: '<button onclick="this.textContent=\'Clicked\'">Frame action</button>' })
  return route.fulfill({ contentType: 'text/html', body: '<!doctype html><html><body style="margin:0;min-height:2000px;background:#f5f6f7"><button id="host-action" style="position:fixed;left:20px;top:20px" onclick="this.textContent=\'Clicked\'">Host action</button><iframe id="business" src="https://child.test/" style="position:absolute;left:100px;top:120px;width:600px;height:420px"></iframe><script src="/embed/assistant.js"></script></body></html>' })
})
const launcher = page.getByRole('button', { name: '打开 AI 助手', exact: true })
const root = page.locator('#aihub-assistant-root')
const settle = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
const position = async () => { await settle(); const b = await launcher.boundingBox(); return { x: b.x, y: b.y } }
const begin = async () => { const b = await launcher.boundingBox(); await page.mouse.move(b.x + 24, b.y + 24); await page.mouse.down() }
const closed = async () => {
  assert.equal(await root.locator('.panel').isVisible(), false, 'Dragging must not open chat')
  assert.equal(await root.locator('.drag-shield').count(), 0, 'Release must remove the shield')
}
try {
  await page.goto('https://host.test/')
  await launcher.evaluate(element => element.addEventListener('pointerdown', event => { window.pointerId = event.pointerId }))
  await begin()
  await page.mouse.move(350, 300, { steps: 12 })
  await page.mouse.up()
  assert.deepEqual(await position(), { x: 326, y: 276 })
  await closed()
  await page.mouse.move(700, 500)
  assert.deepEqual(await position(), { x: 326, y: 276 }, 'Release over iframe must stop dragging')
  await page.frameLocator('#business').getByRole('button').click()
  assert.equal(await page.frameLocator('#business').getByRole('button').textContent(), 'Clicked')

  await launcher.click()
  assert(await root.locator('.panel').isVisible(), 'Click after dragging must open chat')
  await page.getByRole('button', { name: '收起助手', exact: true }).click()
  assert.deepEqual(await position(), { x: 326, y: 276 }, 'Closing chat must preserve position')
  await begin()
  await page.mouse.move(352, 302)
  await page.mouse.up()
  assert(await root.locator('.panel').isVisible(), 'Small pointer jitter must remain a click')
  await page.getByRole('button', { name: '收起助手', exact: true }).click()

  for (const reason of ['blur', 'pointercancel', 'lostcapture', 'buttons-zero', 'pagehide']) {
    await begin()
    await page.mouse.move(280, 330)
    await settle()
    const before = await position()
    await page.evaluate(reason => {
      const element = document.querySelector('#aihub-assistant-root').shadowRoot.querySelector('.launcher')
      if (reason === 'blur' || reason === 'pagehide') window.dispatchEvent(new Event(reason))
      if (reason === 'pointercancel') element.dispatchEvent(new PointerEvent('pointercancel', { pointerId, bubbles: true, composed: true }))
      if (reason === 'lostcapture') element.releasePointerCapture(pointerId)
      if (reason === 'buttons-zero') element.dispatchEvent(new PointerEvent('pointermove', { pointerId, pointerType: 'mouse', buttons: 0, bubbles: true, composed: true }))
    }, reason)
    await page.mouse.up()
    await page.mouse.move(50, 80)
    await closed()
    assert.deepEqual(await position(), before, `${reason} must stop dragging`)
    await page.locator('#host-action').click()
  }
  await begin()
  await page.mouse.move(1200, 1000)
  await page.mouse.up()
  assert.deepEqual(await position(), { x: 844, y: 644 })
  await page.setViewportSize({ width: 390, height: 844 })
  assert.deepEqual(await position(), { x: 334, y: 644 })
  await launcher.click()
  await page.setViewportSize({ width: 320, height: 500 })
  await page.getByRole('button', { name: '收起助手', exact: true }).click()
  assert.deepEqual(await position(), { x: 264, y: 444 }, 'Hidden launcher must be clamped on resize')
  await begin()
  await page.mouse.move(220, 280)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.mouse.up()
  await closed()

  const cdp = await context.newCDPSession(page)
  const beforeTouch = await position()
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: beforeTouch.x + 24, y: beforeTouch.y + 24 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 180, y: 350 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  assert.deepEqual(await position(), { x: 156, y: 326 })
  assert.equal(await page.evaluate(() => scrollY), 0, 'Touch dragging must not scroll the host')
  await closed()
  await mkdir('node_modules/.cache/embed-browser', { recursive: true })
  await page.screenshot({ path: 'node_modules/.cache/embed-browser/launcher-drag-mobile.png', animations: 'disabled' })
  await launcher.focus()
  await page.keyboard.press('Enter')
  assert(await root.locator('.panel').isVisible(), 'Keyboard activation must work after a drag')
  assert.deepEqual(errors, [])
  console.log('Assistant drag passed: mouse/touch, iframe crossing, click threshold, cancellation cleanup, position retention, viewport bounds and keyboard activation.')
} finally { await browser.close() }
