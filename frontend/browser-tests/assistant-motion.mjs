import assert from 'node:assert/strict'
import { readFile, mkdir } from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const source = await readFile('public/embed/assistant.js', 'utf8')
const sprite = await readFile('public/embed/icons/assistant-core.svg', 'utf8')
assert.equal(JSON.parse(source.match(/var cowMarkup = ([^\r\n]*)/)[1]), sprite.replaceAll('\r\n', '\n'), 'Inline cow must match the canonical SVG asset')
const output = path.resolve('node_modules/.cache/assistant-motion')
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 900, height: 650 }, deviceScaleFactor: 2 })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('https://assistant.test/**', route => {
    if (route.request().url().endsWith('.js')) return route.fulfill({ contentType: 'text/javascript; charset=utf-8', body: source })
    return route.fulfill({ contentType: 'text/html', body: '<!doctype html><body style="margin:0;background:#f5f7f6"><script src="/embed/assistant.js"></script></body>' })
  })
  await page.goto('https://assistant.test/')
  const launcher = page.getByRole('button', { name: '打开 AI 助手', exact: true })
  const head = launcher.locator('.head')
  const bounds = await launcher.boundingBox()
  const down = await head.boundingBox()
  assert.notEqual(await launcher.locator('.hoof-left').evaluate(el => getComputedStyle(el).animationName), 'none')
  await launcher.hover()
  await page.waitForTimeout(750)
  const up = await head.boundingBox()
  assert(down.y - up.y > 4, 'The real 60px icon must visibly lift its head')
  assert.deepEqual(await launcher.boundingBox(), bounds, 'The hit area and desk must stay planted')
  assert.equal(await launcher.locator('.hoof-left').evaluate(el => getComputedStyle(el).animationPlayState), 'paused')
  await page.mouse.move(0, 0)
  await page.waitForTimeout(850)
  assert(Math.abs((await head.boundingBox()).y - down.y) < .1, 'Pointer exit must restore the working pose')
  await launcher.hover()
  await page.waitForTimeout(120)
  const partial = await head.boundingBox()
  assert(partial.y < down.y && partial.y > up.y, 'Head lift must interpolate, not jump')
  await page.mouse.move(0, 0)
  await page.waitForTimeout(160)
  await launcher.hover()
  await page.waitForTimeout(750)
  assert(Math.abs((await head.boundingBox()).y - up.y) < .1, 'Rapid hover reversal must settle correctly')
  await page.mouse.move(0, 0)
  await launcher.focus()
  assert(await launcher.evaluate(el => el.classList.contains('attentive')), 'Keyboard focus also looks up')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await head.evaluate(el => getComputedStyle(el).transitionDuration), '0s')
  assert(await launcher.locator('.head,.face,.eyes,.hoof-left,.hoof-right').evaluateAll(els => els.every(el => getComputedStyle(el).animationName === 'none')))
  await page.screenshot({ path: path.join(output, 'cow-launcher.png') })
  await page.setViewportSize({ width: 620, height: 260 })
  await page.evaluate(sprite => {
    document.querySelector('#aihub-assistant-root').remove()
    document.body.innerHTML = '<style>main{display:flex;align-items:center;justify-content:space-evenly;height:260px;background:#f8faf8;font:14px Arial;color:#31594b}section{text-align:center}.large svg{width:160px;height:160px}.small svg{width:48px;height:48px}svg{display:inline-block}</style><main><section class="launcher large">'+sprite+'<div>埋头工作</div></section><section class="launcher attentive large">'+sprite+'<div>抬头看你</div></section><section class="small"><span class="launcher">'+sprite+'</span><span class="launcher attentive">'+sprite+'</span><div>实际 48px</div></section></main>'
  }, sprite)
  await page.screenshot({ path: path.join(output, 'cow-preview.png') })
  assert.deepEqual(errors, [])
  console.log('Passed: real inline icon typing, head lift/interpolation, quick hover reversal, return to work, fixed hit area, keyboard focus and reduced motion.')
} finally { await browser.close() }
